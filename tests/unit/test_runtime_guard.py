def test_enforce_disclosure_injection():
    @enforce(disclosure="AI Generated by Animus Model v6")
    async def generate_response(prompt: str) -> str:
        return "Here is the statistical summary."

    res = asyncio.run(generate_response("summarize data"))
    assert "[AI Generated by Animus Model v6]" in res
    assert "Here is the statistical summary." in res


